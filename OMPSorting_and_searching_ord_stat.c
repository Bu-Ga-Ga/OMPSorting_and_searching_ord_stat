void Merge(int *m1, size_t n1, int *m2, size_t n2, int *r) //Функция для слияния двух отсортированных массиов. Хотим из двух отсортированных массивов сделать один отсортированный
	{
		while(n1>0&&n2>0)
			{	
					if(*m1<*m2)
					{
						*(r++)=*(m1++);
						n1--;
					} 
				else 
					{
						*(r++)=*(m2++);
						n2--;	
					}
			}

		while(n1>0)
			{
				*(r++)=*(m1++);
				n1--;
			}

		while(n2>0)
			{
				*(r++)=*(m2++);
				n2--;
			}			
	}
