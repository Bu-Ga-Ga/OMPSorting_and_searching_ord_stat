#define V m[i]    //i текущий индекс.
#define iL (2*i+1)
#define iR (2*i+2)
#define L m[iL]   //Левый элемент
#define R m[iR]   //Правый Элемент

void Heapify(int *m, size_t n, size_t i)
	{
		while(iR<n)//Пока есть 3 элемента
			{
				if(V>=L && V>=R) return;
				if(L>R)
					{
						SWAP(V,L);
						i=iL;
					}
				else
					{
						SWAP(V,R);
						i=iR;
					}
			}

		if(iL<n)
			{
				if(L>V)
					{
						SWAP(V,L);
					}
			}
	}
void HeapSort(int *a, size_t n)
	{
		size_t i,l;
		for(i=n-2;i>0;i--) Heapify(a,n,i);
		Heapify(a,n,0);
		for(l=n-1;l>=1;l--)
			{
				SWAP(a[0],a[l]);
				Heapify(a,l,0);
			}			
	}
