void BubbleSort(int *m, size_t n) // Вместо size_t можно и int
	{
		size_t i,j;

		for(i=0;i<n;i++)
			for(j=1;j<n;j++)
				if(m[j-1]>m[j]) SWAP(m[j-1],m[j]);
	}

