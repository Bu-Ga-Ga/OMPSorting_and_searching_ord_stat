void QSort1_(int *m,size_t p,size_t q)//Работаем от элементов p до q.
	{
		size_t i,j;  //M=m[j];(Взяли j как псевдомедиану) [p,i-1]<=M<=[j,q]
		if (p>=q) return;
		i=p;
		j=q;

		while(1)
			{
				while(m[i]<m[j]) i++;//M=m[j]; [p,i-1]<=M<=[j,q]
				SWAP(m[i],m[j]);     //M=m[i]; [p,i]<=M<=[j,q] теперь псевдомедиана из j элемента перенеслась в i.
				j--;                 //M=m[i]; [p,i]<=M<=[j+1,q]. j-- гарантирует что j+1 будет в гранницах нашего массива.
				                     // Если j никуда не сдвинулась, то в первый блок if мы не попадем.
				if(i>=j)// (1)Если Встретились (Можем либо вастретиться, либо перескачить)
					{
						//i==j:   //M=m[j]; [p,j]<=M<=[j+1,q]
						//i=j=1:  //M=m[j]; [p,j+1]<=M<=[j+1,q] => [p,j]<=M<=[j+1,q]
						QSort1_(m,p,j);
						QSort1_(m,j+1,q);
						return;
					}

				while(m[i]<m[j]) j--; //M=m[i]; [p,i]<=M<=[j+1,q]
				SWAP(m[i],m[j]);      //M=m[j]; [p,i]<=M<=[j,q]
				i++;                  //M=m[j]; [p,i-1]<=M<=[j,q] Совпадает с тем, что было в начале.//i++ гарантирует что i-1 будет в гранницах нашего массива.

				if(i>=j) //(2)
					{   //Два случая:
						//i==j:       //M=m[j]; [p,j-1]<=M<=[j,q]  =>  [p,j]<=M<=[j,q]
						//i=j+1:      //M=m[j]; [p,j]<=M<=[j,q]
						QSort1_(m,p,j);
						QSort1_(m,j+1,q);
						return;
					}
			}

	}
