void Sort2(int *m, size_t n, int *t)
	{
		size_t k,k2,i;//в конце будет пара кусков один длины k а другой может быть короче.

		for(k=1;k<n;k*=2)
			{
				for(i=0;i+k<n;i+=2*k)//Второй кусок начинается с места i+k. 
					{
						k2=MIN(k,n-(i+k));//если второй кусок короче. k2-длина второго куска (n-(i+k)-Длинна куска от позиции i+k до конца)
						Merge(m+i,k,m+i+k,k2,t+i); //Получаем кусок длины k+k2
						memcpy(m+i,t+i,(k+k2)*sizeof(*m));
                    }

			}
	}
