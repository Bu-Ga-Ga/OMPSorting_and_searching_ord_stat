void Sort1OMP(int *m, size_t n, int *t)
	{                                 
			int n1,n2;                
		if(n<=1) return;                                                                                      
		n1=n/2;
		n2=n-n1;
		#pragma omp parallel sections //говорим что дальше пойдут параллельные секции в блоке из {}.
	    	{
	    		#pragma omp section //Указываем секции
				{Sort1(m,n1,t);}          //Sort1 здесь не пересекаются, значит можем распаралелить.
				#pragma omp section       // В данном случае используем 2 потока.
				{Sort1(m+n1, n2, t+n1);}
			}
		Merge(m,n1,m+n1,n2,t); 
		memcpy(m,t,n*sizeof(*m)); 
	}
