void Sort1(int *m, size_t n, int *t) //Сортировка слиянием с рекурсией. t-временный массив
	{                                 //Берем массив. Если он длины <=1 то ничего делать не надо.Выходим.
					                   //В другом случае бьем его на две половины и вызываем ту же самую функцию. Эта функция отсортирует эти половинки.И мы их сливаем с помощью слияния.
		int n1,n2;  //Длины кусков массивов                
		if(n<=1) return;
		n1=n/2;
		n2=n-n1;
		Sort1(m,n1,t);
		Sort1(m+n1, n2, t+n1);
		Merge(m,n1,m+n1,n2,t); //сливаем в массив t
		memcpy(m,t,n*sizeof(*m)); //Перебрасываем из t в m.
	}
